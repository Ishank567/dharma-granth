function gita(part: {
  id: string;
  chapter: number;
  verse: number;
  sanskrit: string;
  hindi: string;
  english: string;
  setting: string;
  settingHi: string;
}): ScriptureReference {
  return {
    id: part.id,
    scriptureId: 'bhagavadgita',
    scriptureName: 'Bhagavad Gita',
    scriptureNameHi: 'भगवद्गीता',
    chapterNumber: part.chapter,
    verseNumber: part.verse,
    referenceDisplay: `Bhagavad Gita ${part.chapter}.${part.verse}`,
    referenceDisplayHi: `भगवद्गीता ${part.chapter}.${part.verse}`,
    sanskritDevanagari: part.sanskrit,
    sanskritTransliteration: '',
    literalTranslationHi: part.hindi,
    literalTranslationEn: part.english,
    traditionalContext: {
      speaker: 'Shri Krishna',
      addressee: 'Arjuna',
      setting: part.setting,
      settingHi: part.settingHi,
      commentaryNote: '',
      commentaryNoteHi: '',
    },
    readerHref: `/scripture/bhagavadgita/chapter/${part.chapter}/verse/${part.verse}/`,
  };
}

