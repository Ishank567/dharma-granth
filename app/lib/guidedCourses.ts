export function getAllGuidedCourseDefinitions(): GuidedCourseDefinition[] {
  return GUIDED_COURSE_DEFINITIONS;
}

export function getGuidedCourseDefinition(bookSlug: string): GuidedCourseDefinition | undefined {
  return GUIDED_COURSE_DEFINITIONS.find((course) => course.bookSlug === bookSlug);
}

export function hasGuidedCourse(bookSlug: string): boolean {
  return GUIDED_COURSE_DEFINITIONS.some((course) => course.bookSlug === bookSlug);
}

function buildModuleHeaderSummary(courseTitle: string, module: GuidedCourseModuleDefinition): string {
  const reflectionPrompt = module.reflection.replace(/[?।.!]+$/g, '');
  return `${module.summary} ${courseTitle} के इस अध्ययन-खंड का मुख्य मनन-विषय है: ${reflectionPrompt}। अभ्यास का सूत्र: ${module.practice}`;
}

export function resolveGuidedCourse(
  course: GuidedCourseDefinition,
  totalVerses: number,
  versesPerPage = 20
): ResolvedGuidedCourse {
  const safeTotal = Math.max(totalVerses, 1);
  const moduleCount = course.modules.length;

  const modules = course.modules.map((module, index) => {
    const startVerseNumber = Math.floor((index * safeTotal) / moduleCount) + 1;
    const endVerseNumber = Math.max(
      startVerseNumber,
      Math.floor(((index + 1) * safeTotal) / moduleCount)
    );
    const anchorVerseNumber = Math.min(
      safeTotal,
      Math.max(startVerseNumber, Math.round((startVerseNumber + endVerseNumber) / 2))
    );

    return {
      ...module,
      headerSummary: module.headerSummary ?? buildModuleHeaderSummary(course.title, module),
      order: index + 1,
      startVerseNumber,
      endVerseNumber,
      anchorVerseNumber,
      estimatedPage: Math.max(1, Math.ceil(startVerseNumber / versesPerPage)),
    };
  });

  return {
    ...course,
    totalVerses: safeTotal,
    modules,
  };
}

export function getGuidedCourseContextForVerse(
  bookSlug: string,
  verseNumber: number,
  totalVerses: number
): GuidedCourseVerseContext | undefined {
  const course = getGuidedCourseDefinition(bookSlug);
  if (!course) {
    return undefined;
  }

  const resolvedCourse = resolveGuidedCourse(course, totalVerses);
  const matchedModule = resolvedCourse.modules.find(
    (item) => verseNumber >= item.startVerseNumber && verseNumber <= item.endVerseNumber
  );

  if (!matchedModule) {
    return undefined;
  }

  return {
    courseTitle: resolvedCourse.title,
    tradition: resolvedCourse.tradition,
    moduleTitle: matchedModule.title,
    moduleSummary: matchedModule.summary,
    headerSummary: matchedModule.headerSummary,
    reflection: matchedModule.reflection,
    practice: matchedModule.practice,
  };
}