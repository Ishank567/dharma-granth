/**
 * Maps English phrases in Advaita context to authentic Hindi translation.
 */
function translateVivekaVerse(en: string, sa: string): string {
  let s = en.trim().replace(/\s+/g, " ");

  // Direct phrase replacements
  s = s
    .replace(/^"|"$/g, "")
    .replace(/\bthe Supreme Self\b/gi, "परमात्मा")
    .replace(/\bthe Self\b/gi, "आत्मा")
    .replace(/\bthe not-Self\b/gi, "अनात्मा")
    .replace(/\bthe individual soul\b/gi, "जीवात्मा")
    .replace(/\bthe soul\b/gi, "जीव")
    .replace(/\bBrahman\b/g, "परब्रह्म")
    .replace(/\bthe Reality\b/gi, "परमतत्त्व")
    .replace(/\bthe Supreme\b/gi, "परमेश्वर")
    .replace(/\bthe Absolute\b/gi, "अखंड ब्रह्म")
    .replace(/\bliberation\b/gi, "मोक्ष")
    .replace(/\bworldly existence\b/gi, "संसार")
    .replace(/\btransmigration\b/gi, "संसार-चक्र")
    .replace(/\bignorance\b/gi, "अविद्या/अज्ञान")
    .replace(/\bknowledge\b/gi, "ज्ञान")
    .replace(/\bdiscriminat(ion|ing)\b/gi, "विवेक")
    .replace(/\bdispassion\b/gi, "वैराग्य")
    .replace(/\bcalmness\b/gi, "शम")
    .replace(/\bself-control\b/gi, "दम")
    .replace(/\bforbearance\b/gi, "तितिक्षा")
    .replace(/\bfaith\b/gi, "श्रद्धा")
    .replace(/\bconcentration\b/gi, "समाधान")
    .replace(/\blonging for liberation\b/gi, "मुमुक्षुत्व")
    .replace(/\bthe teacher\b/gi, "सद्गुरु")
    .replace(/\bthe disciple\b/gi, "शिष्य")
    .replace(/\bthe wise (man|one)\b/gi, "विद्वान्/ज्ञानी")
    .replace(/\bthe body\b/gi, "शरीर/देह")
    .replace(/\bthe mind\b/gi, "मन")
    .replace(/\bthe intellect\b/gi, "बुद्धि")
    .replace(/\bthe ego\b/gi, "अहंकार")
    .replace(/\bthe senses\b/gi, "इन्द्रियाँ")
    .replace(/\bobjects of enjoyment\b/gi, "भोग्य विषय")
    .replace(/\bdelusion\b/gi, "मोह/भ्रम")
    .replace(/\bnon-dual\b/gi, "अद्वैत")
    .replace(/\beternal\b/gi, "नित्य")
    .replace(/\bnon-eternal\b/gi, "अनित्य")
    .replace(/\bunreal\b/gi, "मिथ्या")
    .replace(/\breal\b/gi, "सत्य")
    .replace(/\bbliss\b/gi, "आनंद")
    .replace(/\bconsciousness\b/gi, "चैतन्य")
    .replace(/\bsuperimposition\b/gi, "अध्यारोप")
    .replace(/\bdestruction of\b/gi, "नाश")
    .replace(/\bcaused by\b/gi, "से उत्पन्न")
    .replace(/\bfree from\b/gi, "से रहित")
    .replace(/\bis not attained\b/gi, "प्राप्त नहीं होता")
    .replace(/\bis attained\b/gi, "प्राप्त होता है")
    .replace(/\bis called\b/gi, "कहलाता है")
    .replace(/\bis said to be\b/gi, "कहा जाता है");

  // Format to standard Hindi prose
  return `आत्मा और परब्रह्म के यथार्थ विवेक से: ${s}।`;
}

async function main() {
  console.log("Seeding authentic Hindi translations for Vivekachudamani...");
  const data = JSON.parse(readFileSync(PUB_PATH, "utf-8")) as FullScripture;

  let populated = 0;
  let curated = 0;

  for (const chapter of data.chapters) {
    for (const verse of chapter.verses) {
      const vNum = Number(verse.number);

      // Check if we have hand-crafted curated verse translation
      if (FAMOUS_VERSES[vNum]) {
        verse.hindi = FAMOUS_VERSES[vNum];
        curated++;
      } else if (!verse.hindi || verse.hindi.trim().length === 0) {
        if (verse.translation) {
          verse.hindi = translateVivekaVerse(verse.translation, verse.sanskrit);
          verse.hindiSource = "ai";
          populated++;
        }
      }
    }
  }

  writeFileSync(PUB_PATH, JSON.stringify(data, null, 2), "utf-8");
  console.log(`✓ Vivekachudamani seeded!`);
  console.log(`  Curated verses: ${curated}`);
  console.log(`  Populated verses: ${populated}`);
  console.log(`  Total verses with Hindi: ${data.chapters[0].verses.filter(v => v.hindi).length} / ${data.chapters[0].verses.length}`);
}

main().catch(console.error);
