const bookPath = 'public/data/scriptures-full/shvetashvatara.json';
const book = JSON.parse(fs.readFileSync(bookPath, 'utf8'));
let hindiSet = 0;
for (const ch of book.chapters) {
  for (const v of ch.verses) {
    const key = `${ch.number}:${v.number}`;
    const row = FILL[key];
    if (!row) continue;
    if (!(v.hindi || '').trim()) {
      v.hindi = row.hindi;
      hindiSet++;
    }
  }
}
fs.writeFileSync(bookPath, JSON.stringify(book));
const commentary = {};
for (const [key, row] of Object.entries(FILL)) {
  commentary[key] = { explanation: row.explanation, science: row.science };
}
fs.writeFileSync(
  'data/hi-commentary/shvetashvatara-rest.json',
  JSON.stringify(commentary, null, 2),
);
