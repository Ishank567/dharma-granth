function buildPrakaranFiles(num, title, speaker, data) {
  // 1. JSON (Format B)
  const jsonStr = JSON.stringify(data, null, 2);
  fs.writeFileSync(`data/ashtavakra/ashtavakra_prakaran_${num}.json`, jsonStr, 'utf8');

  // 2. Markdown / TXT (Format A)
  const mdLines = [];
  mdLines.push(`# अष्टावक्र गीता — ${title}`);
  mdLines.push(`**टीकाकार:** रायबहादुर बाबू जालिमसिंह`);
  mdLines.push(`**वक्ता:** ${speaker}`);
  mdLines.push(`**श्लोक संख्या:** १ से ${data.length}`);
  mdLines.push(`\n---\n`);

  for (const v of data) {
    mdLines.push(`## श्लोक ${v.verse_number}\n`);
    mdLines.push(`**वक्ता:** ${v.speaker} ।\n`);
    mdLines.push(`**मूलम् ।**`);
    mdLines.push(v.mula_sloka.split('\n').map(l => `> ${l}`).join('  \n'));
    mdLines.push(`\n**पदच्छेदः ।**\n${v.padachheda.join(', ')} ।\n`);
    mdLines.push(`**अन्वयः एवं शब्दार्थः ।**`);
    mdLines.push(`| संस्कृत पद | हिन्दी अर्थ |`);
    mdLines.push(`| :--- | :--- |`);
    for (const item of v.anvaya_sabdartha) {
      mdLines.push(`| **${item.sanskrit}** | ${item.hindi} |`);
    }
    mdLines.push(`\n**भावार्थः एवं टीका (रायबहादुर बाबू जालिमसिंह) ।**\n${v.bhavartha}\n`);
    if (v.citations && v.citations.length > 0) {
      mdLines.push(`**उद्धरण एवं संदर्भ ।**`);
      for (const c of v.citations) {
        mdLines.push(`- *${c.source}:* "${c.text}"`);
      }
    }
    mdLines.push(`\n---\n`);
  }

  const mdStr = mdLines.join('\n');
  fs.writeFileSync(`docs/ashtavakra/ashtavakra_prakaran_${num}.md`, mdStr, 'utf8');
  fs.writeFileSync(`docs/ashtavakra/ashtavakra_prakaran_${num}.txt`, mdStr, 'utf8');

  console.log(`Generated Prakaran ${num}: ${data.length} verses (JSON: ${jsonStr.length} bytes, MD: ${mdStr.length} bytes)`);
}

